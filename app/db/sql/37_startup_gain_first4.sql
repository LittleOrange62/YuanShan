-- 37_startup_gain_first4.sql
-- `analytics.startup_volume_profile` 加一列 `gain_first4`：
--   **以前一天的收盘价为基准，前四根（含启动日那根）的累计涨幅。**
--
-- 为什么加（用户 2026-10-15 点名：「这里的条件再加一个，就是『近 3 个月出现过 4 板及以上
--   （连续涨停 ≥4 天）的票』……再加一条，就是 4 天涨幅大于 45% 的票，也就是第 0 天收盘价到
--   第 3 天收盘价，初始计算的值要以这 4 天前一天的收盘价作为基准。
--   之前的条件 4 板及以上（连续涨停 ≥4 天）其实也是基于第 0 天的收盘价作为基准的」）：
--   1. 那一档母体原来只有一个门槛：**段长 ≥ 4**。段长相同、强度可以差很远 ——
--      4 个 10% 涨停 = +46.4%，而"两天涨停 + 两天磨"凑出的 4 天同样算 4 板。
--      用户要的就是把后者筛掉：**四段加起来必须 >45%**（≈ 4 个满涨停，1.10^4 − 1 = 46.41%）。
--   2. 这一列与 `trigger_gain` 不是同一个数，别混：`trigger_gain` 覆盖**整段**（段长可以是 5、6、7 天），
--      `gain_first4` 只看**段内前四根**。段长正好是 4 时两者相等（实测 2026-10-09 那场三只都相等：
--      002696 +46.62%、603096 +46.48%、002343 +46.47%）；段长更长时 gain_first4 必然小于 trigger_gain。
--   3. 基准那条与既有判据同源：写侧 `runs` 里 base 优先取 `pre_close`（除权日它是除权参考价，
--      与 close 同基），只有它为空/为 0 才退回上一根收盘 —— 停牌复牌日库里 pre_close 是空的
--      （实测 600825.SH 2026-09-21 复牌 7 连板）。缺基准就整段交 NULL，**不硬算也不按 0 算**。
--
-- 为什么 `jump40` 那一档也顺手有值：它的 `trigger_gain` 本来就是 `close / lag(close,4) − 1`
--   —— 同一把尺子（以前 4 根那天收盘为基准的四段涨幅），所以这一列对它等于 `trigger_gain`。
--   两类母体的启动日语义不同（A 类启动日 = 首板日；B 类 = 触发窗口的最后一天，见 26 号 DDL 注释），
--   这一列只说"涨幅怎么算出来的"，不改变启动日那条口径。
--
-- 版本：`sv-2` 不升号。加的是**第三类母体 + 一列附加读数**，board4 / jump40 原有行的判据一个字没动，
--   重算只会把同一批行的这一列补上（旧行留在原地，不删 —— 见 startup_volume.py 那句"这里不删任何历史行"）。
--   重算窗口之外的旧行这一列是 NULL，读侧交 null，界面显示 —，意思是"这一行没算过"，不是"涨幅是 0"。

alter table analytics.startup_volume_profile add column if not exists gain_first4 numeric(10,4);

comment on column analytics.startup_volume_profile.gain_first4 is
  '前四根（含启动日）累计涨幅：基准 = 启动日前一天收盘（pre_close 优先，缺则上一根收盘），分子 = 段内第 4 根收盘。'
  '与 trigger_gain 的区别：后者覆盖整段（段长可 >4），这一列只取前四根；段长正好 4 时两者相等。'
  'NULL = 段长不足 4 根、或第 4 根/基准价缺失（不硬算、不按 0 算）。第三类母体 board4_45 就是这一列 > 0.45。';
